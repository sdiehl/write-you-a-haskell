"""Regenerate character tables: python3 tools/unicode.py UnicodeData.txt.
Source: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
The caller supplies the pinned Unicode 17.0 database; no network during builds.
"""
import hashlib
import sys
from pathlib import Path
raw = Path(sys.argv[1]).read_bytes()
rows = [line.split(';') for line in raw.decode().splitlines()]
chars = {}
for row in rows:
    n = int(row[0], 16)
    if row[1].endswith(', First>'):
        start = n
    elif row[1].endswith(', Last>'):
        for k in range(start, n + 1):
            chars[k] = row[2]
    else:
        chars[n] = row[2]
def quoted(ns):
    return '"' + ''.join('\\u{' + hex(n)[2:] + '}' for n in ns) + '"'
def ranges(categories):
    out = []
    for n, cat in chars.items():
        if cat not in categories:
            continue
        if out and n == out[-1] + 1:
            out[-1] = n
        else:
            out.extend([n, n])
    return out
out = ['-- Unicode 17.0.0 tables, generated by tools/unicode.py.',
       '-- UnicodeData.txt SHA-256: ' + hashlib.sha256(raw).hexdigest()]
for name, cats in [('isAlpha', ['Lu','Ll','Lt','Lm','Lo']), ('isUpper',['Lu','Lt']), ('isLower',['Ll'])]:
    out.append(f'{name} c = _charRanges c (unpack {quoted(ranges(cats))})')
for name, col in [('toUpper',12),('toLower',13)]:
    pairs = [n for r in rows if r[col] for n in [int(r[0],16),int(r[col],16)]]
    out.append(f'{name} c = _charMap c (unpack {quoted(pairs)})')
out += [
    'isDigit c = c >= \'0\' && c <= \'9\'',
    "isSpace c = let { n = ord c; } in (n >= 9 && n <= 13) || n == 32 || n == 160 || n == 5760 || (n >= 8192 && n <= 8202) || n == 8232 || n == 8233 || n == 8239 || n == 8287 || n == 12288",
    '_charRanges c (a:b:rest) = if c < a then False else if c <= b then True else _charRanges c rest',
    '_charRanges c _ = False',
    '_charMap c (a:b:rest) = if c < a then c else if c == a then b else _charMap c rest',
    '_charMap c _ = c',
]
Path(__file__).resolve().parent.parent.joinpath('unicode.fun').write_text('\n'.join(out)+'\n')
